function sys = sys_config()
% SYS_CONFIG  系统级物理参数(TA建议的聚合模型, 无量纲频偏形式)
%
% 模型(二状态等值, 助教2026-09-21建议):
%   2H * dx/dt = -d - D*x + p        (摆动方程, x为无量纲频偏)
%   Tg * dp/dt = -p + clip(-x/R, 0, p_max)   (调速器一阶惯性+限幅)
%   频率 f = f_nom * (1 + x),  初值 x(0)=p(0)=0
%
% 参数说明:
%   f_nom : 额定频率(Hz),中国标准50Hz
%   S_base: 基准容量(MVA)
%   H     : 惯性常数(s),聚合惯量
%   D     : 负荷阻尼系数(pu),无量纲频偏下的阻尼
%   R     : 频率下垂系数(pu),调频稳态增益(1/R)
%   Tg    : 调速器时间常数(s),一次调频响应惯性
%   p_max : 调频最大备用功率(pu),助教建议固定0.1
%
% 注意:本模型不含调频死区(助教建议的首版简化);
%       无量纲频偏 x = (f - f_nom)/f_nom, 与旧版Hz偏差形式不同。

sys.f_nom  = 50;        % 额定频率 50 Hz
sys.S_base = 100;       % 基准容量 100 MVA
sys.H      = 4;         % 惯性常数 4 s(默认值,批量仿真时被参数空间覆盖)
sys.D      = 1;         % 阻尼系数 1 pu
sys.R      = 0.05;      % 下垂系数 0.05 pu
sys.Tg     = 0.5;       % 调速器时间常数 0.5 s
sys.p_max  = 0.1;       % 调频备用上限 0.1 pu(助教建议固定值)
end
