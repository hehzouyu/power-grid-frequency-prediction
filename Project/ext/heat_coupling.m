function [t, f, nadir] = heat_coupling(sys, sim, H_vhp)
% HEAT_COUPLING  热-电耦合场景仿真:热泵提供虚拟惯量
%
% 大白话:思路来自微分方程建模里"参数可变"的思想——
%        热泵、电动汽车这些灵活负荷,控制系统可以模拟出"虚拟惯性":
%        频率一跌,它们立刻少用电,效果上相当于给电网多添了旋转质量。
%        数学处理非常简单:把附加惯量 H_vhp 加到等效惯量上,
%        摇摆方程本身一个字不用改——这正是微分方程"结构不变、参数可调"
%        建模思想的直接体现。
%
% 输入:
%   sys   : 系统参数
%   sim   : 仿真参数
%   H_vhp : 热泵提供的虚拟惯量(等效附加惯性常数,秒)
%
% 输出:
%   t, f, nadir : 与 simulate_freq 相同
%
% 用途:把本函数生成的曲线喂给第3、4步已有的特征提取和模型流程,
%       验证"训练好的模型在新场景下还能不能用"——这就是迁移/鲁棒性验证。

s = sys;
s.H = sys.H + H_vhp;            % 虚拟惯量 = 附加惯性常数
[t, f, nadir] = simulate_freq(s, sim);
end
