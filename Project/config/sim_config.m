function sim = sim_config()
% SIM_CONFIG  仿真过程参数(按助教建议:T=20s, 采样0.02s, 观察截止0.5s)
%
% 输出 sim: 结构体
%   t_end   : 仿真总时长(s),T=20,覆盖最低点出现的整个区间
%   dt      : 采样周期(s),0.02s(助教建议)
%   t_dist  : 扰动发生时刻(s),第1秒施加阶跃功率缺额
%   tau_obs : 观察截止(s),特征只允许用扰动后前0.5秒的数据
%             标签取 tau_obs 之后的最低点(助教方法学要求)
%   dP      : 默认扰动功率缺额(pu,无量纲基准),批量仿真时被覆盖
%   rel_tol : 积分相对误差限

sim.t_end   = 20;       % 总时长 20 s
sim.dt      = 0.02;     % 采样周期 0.02 s(共1001个点)
sim.t_dist  = 1;        % 第1秒时发生阶跃扰动
sim.tau_obs = 0.5;      % 观察截止:扰动后0.5秒(特征窗口上限)
sim.dP      = 0.05;     % 默认缺额 0.05 pu
sim.rel_tol = 1e-8;     % 积分精度(较严,保证初始斜率校验可靠)
end
